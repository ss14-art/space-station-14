            TabContainer.SetTabTitle(_modifyUiTab, Loc.GetString("genetics-console-tab-ui"));
            TabContainer.SetTabTitle(_modifySeTab, Loc.GetString("genetics-console-tab-se"));
            TabContainer.SetTabTitle(_transferBuffersTab, Loc.GetString("genetics-console-tab-buffers"));
            TabContainer.SetTabTitle(_rejuvenatorsTab, Loc.GetString("genetics-console-tab-rejuvenators"));

            _mainTabContainer.CurrentTab = 1;

            _irradiateButton.OnPressed += _ =>
            {
                if (_lastSelectedWasUi && _lastSelectedUiBlock != -1)
                    OnIrradiateBlock?.Invoke(_lastSelectedUiBlock, true);
                else if (!_lastSelectedWasUi && _lastSelectedSeBlock != -1)
