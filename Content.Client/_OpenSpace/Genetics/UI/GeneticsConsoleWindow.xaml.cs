        private int _lastSelectedUiBlock = -1;
        private int _lastSelectedSeBlock = -1;
        private bool _lastSelectedWasUi;

        public void UpdateState(GeneticsConsoleBoundUserInterfaceState state)
        {
            _occupantNameLabel.Text = state.OccupantName;
            _doorLockButton.Disabled = !state.HasScanner;
            _doorLockButton.Pressed = state.ScannerLocked;
            _doorLockButton.Text = state.ScannerLocked
                ? Loc.GetString("genetics-console-lock-locked")
                : Loc.GetString("genetics-console-lock-unlocked");
            _occupantStatusLabel.Text = state.IsOccupantAlive
                ? Loc.GetString("genetics-console-status-alive")
                : Loc.GetString("genetics-console-status-dead");
            _occupantStatusLabel.FontColorOverride = state.IsOccupantAlive ? Color.Green : Color.Red;

            _healthBar.MaxValue = (float)state.MaxHealth;
            _healthBar.Value = (float)state.CurrentHealth;
            float healthPercent = (state.MaxHealth > 0) ? ((float)state.CurrentHealth / (float)state.MaxHealth) : 0;
            _healthLabel.Text = $"{healthPercent:P0}";

            _radiationBar.MaxValue = 100f; 
            _radiationBar.Value = state.RadiationExposure;
            _radiationLabel.Text = $"{state.RadiationExposure}%";

            _lastSelectedUiBlock = state.SelectedUiBlock;
            _lastSelectedSeBlock = state.SelectedSeBlock;
            _lastSelectedWasUi = _mainTabContainer.CurrentTab == FindTabIndex(_modifyUiTab);
            PopulateEnzymeGrid(state.SeDna, state.SelectedSeBlock);
            PopulateUIGrid(state.UiDna, state.SelectedUiBlock);

            _irradiateButton.Disabled = (_lastSelectedUiBlock == -1 && _lastSelectedSeBlock == -1);
            _uiIrradiateButton.Disabled = _lastSelectedUiBlock == -1;

            if (state.HasBeaker)
            {
                _beakerLabel.Text = state.BeakerLabel;
                _beakerVolumeLabel.Text = Loc.GetString("genetics-console-beaker-volume",
                    ("current", state.BeakerCurrentVolume),
                    ("max", state.BeakerMaxVolume));
                _ejectBeakerButton.Disabled = false;
                _inject5Button.Disabled = state.BeakerCurrentVolume < 5;
                _inject10Button.Disabled = state.BeakerCurrentVolume < 10;
                _inject20Button.Disabled = state.BeakerCurrentVolume < 20;
                _inject30Button.Disabled = state.BeakerCurrentVolume < 30;
                _inject50Button.Disabled = state.BeakerCurrentVolume < 50;
                _injectAllButton.Disabled = state.BeakerCurrentVolume <= 0;
            }
            else
            {
                _beakerLabel.Text = Loc.GetString("genetics-console-beaker-missing");
                _beakerVolumeLabel.Text = Loc.GetString("genetics-console-beaker-volume-empty");
                _ejectBeakerButton.Disabled = true;
                _inject5Button.Disabled = true;
                _inject10Button.Disabled = true;
                _inject20Button.Disabled = true;
                _inject30Button.Disabled = true;
                _inject50Button.Disabled = true;
                _injectAllButton.Disabled = true;
            }

            UpdateTransferBuffers(state);
        }

        private void InitializeTransferBuffers()
        {
            _transferBuffersContainer.DisposeAllChildren();

            for (var i = 0; i < 6; i++)
            {
                var rowContainer = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    SeparationOverride = 2
                };

                var nameLabel = new Label
                {
                    Text = Loc.GetString("genetics-console-buffer-label",
                        ("index", i + 1),
                        ("name", Loc.GetString("genetics-console-buffer-empty"))),
                    StyleClasses = { "LabelSubHeading" }
                };

                var buttonsRow = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    SeparationOverride = 4
                };

                var uiButton = new Button { Text = Loc.GetString("genetics-console-button-ui"), MinWidth = 110 };
                var uiSeButton = new Button { Text = Loc.GetString("genetics-console-button-ui-se"), MinWidth = 160 };
                var seButton = new Button { Text = Loc.GetString("genetics-console-button-se"), MinWidth = 110 };
                var transferButton = new Button { Text = Loc.GetString("genetics-console-button-transfer"), MinWidth = 90 };
                var syringeButton = new Button { Text = Loc.GetString("genetics-console-button-syringe"), MinWidth = 90 };

                var bufferIndex = i;
                uiButton.OnPressed += _ => OnStoreBuffer?.Invoke(bufferIndex, GeneticsBufferCopyMode.UiOnly);
                uiSeButton.OnPressed += _ => OnStoreBuffer?.Invoke(bufferIndex, GeneticsBufferCopyMode.UiAndSe);
                seButton.OnPressed += _ => OnStoreBuffer?.Invoke(bufferIndex, GeneticsBufferCopyMode.SeOnly);
                transferButton.OnPressed += _ => OnTransferBuffer?.Invoke(bufferIndex, GeneticsBufferTransferTarget.Subject);
                syringeButton.OnPressed += _ => OnTransferBuffer?.Invoke(bufferIndex, GeneticsBufferTransferTarget.Syringe);

                buttonsRow.AddChild(uiButton);
                buttonsRow.AddChild(uiSeButton);
                buttonsRow.AddChild(seButton);
                buttonsRow.AddChild(transferButton);
                buttonsRow.AddChild(syringeButton);

                rowContainer.AddChild(nameLabel);
                rowContainer.AddChild(buttonsRow);

                _transferBuffersContainer.AddChild(rowContainer);

                _transferBufferRows.Add(new TransferBufferRow(nameLabel, uiButton, uiSeButton, seButton, transferButton, syringeButton));
            }
        }

        private void UpdateTransferBuffers(GeneticsConsoleBoundUserInterfaceState state)
        {
            for (var i = 0; i < _transferBufferRows.Count; i++)
            {
                var row = _transferBufferRows[i];
                var hasSubject = state.HasSubject;
                var hasSyringe = state.HasSyringe;

                string name = Loc.GetString("genetics-console-buffer-empty");
                bool hasUi = false;
                bool hasSe = false;

                if (i < state.TransferBuffers.Count)
                {
                    var buffer = state.TransferBuffers[i];
                    name = string.IsNullOrWhiteSpace(buffer.SubjectName)
                        ? Loc.GetString("genetics-console-buffer-empty")
                        : buffer.SubjectName;
                    hasUi = buffer.HasUi;
                    hasSe = buffer.HasSe;
                }

                var flags = string.Empty;
                if (hasUi)
                    flags = Loc.GetString("genetics-console-flag-ui");
                if (hasSe)
                    flags = string.IsNullOrEmpty(flags)
                        ? Loc.GetString("genetics-console-flag-se")
                        : $"{flags}, {Loc.GetString("genetics-console-flag-se")}";

                var display = flags.Length > 0 ? $"{name} ({flags})" : name;
                row.NameLabel.Text = Loc.GetString("genetics-console-buffer-label",
                    ("index", i + 1),
                    ("name", display));

                var hasData = hasUi || hasSe;
                row.UiButton.Disabled = !hasSubject;
                row.UiSeButton.Disabled = !hasSubject;
                row.SeButton.Disabled = !hasSubject;
                row.TransferButton.Disabled = !hasData || !hasSyringe;
                row.SyringeButton.Disabled = !hasData || !hasSyringe;
            }
        }

