                UiSeButton = uiSeButton;
                SeButton = seButton;
                TransferButton = transferButton;
                SyringeButton = syringeButton;
            }
        }

        private int FindTabIndex(Control tab)
        {
            for (var i = 0; i < _mainTabContainer.ChildCount; i++)
            {
                if (_mainTabContainer.GetChild(i) == tab)
                    return i;
            }

            return -1;
        }

        private void PopulateEnzymeGrid(Dictionary<int, string> dna, int selectedBlock)
        {
            _enzymeGrid.DisposeAllChildren();

            for (int i = 0; i < 55; i++)
            {
                var blockContainer = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Margin = new Thickness(2),
                    HorizontalExpand = true
                };

                var isSelected = i == selectedBlock;

                blockContainer.AddChild(new Label
                {
                    Text = (i + 1).ToString(),
                    MinWidth = 30,
                    Align = Label.AlignMode.Right,
                    VAlign = Label.VAlignMode.Center
                });

                blockContainer.AddChild(new Control { MinWidth = 5 });

                string hexBlock = dna.ContainsKey(i) ? dna[i] : "---";
                
                while (hexBlock.Length < 3)
                    hexBlock += "-";
                
                for (int subIndex = 0; subIndex < 3; subIndex++)
                {
                    string hexValue = hexBlock.Length > subIndex ? hexBlock[subIndex].ToString() : "-";
                    
                    var button = new Button
                    {
                        Text = hexValue,
                        MinWidth = 35,
                        MinHeight = 35,
                        Margin = new Thickness(1, 0, 1, 0),
                        StyleClasses = { "OpenLeft" },
                        ToggleMode = true,
                        Pressed = isSelected
                    };

                    int blockIndex = i;
                    int currentSubIndex = subIndex;
                    
                    button.OnPressed += _ =>
                    {
                        _lastSelectedSeBlock = blockIndex;
                        _lastSelectedWasUi = false;
                        button.Pressed = true;
                        OnSelectBlock?.Invoke(blockIndex, false);
                    };

                    blockContainer.AddChild(button);
                }

                _enzymeGrid.AddChild(blockContainer);
            }
        }
        
