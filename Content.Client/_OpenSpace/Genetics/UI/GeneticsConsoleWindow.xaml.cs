            _inject5Button = this.FindControl<Button>("Inject5Button");
            _inject10Button = this.FindControl<Button>("Inject10Button");
            _inject20Button = this.FindControl<Button>("Inject20Button");
            _inject30Button = this.FindControl<Button>("Inject30Button");
            _inject50Button = this.FindControl<Button>("Inject50Button");
            _injectAllButton = this.FindControl<Button>("InjectAllButton");
            _ejectBeakerButton = this.FindControl<Button>("EjectBeakerButton");
            _doorLockButton = this.FindControl<Button>("DoorLockButton");
            _occupantNameLabel = this.FindControl<Label>("OccupantNameLabel");
            _occupantStatusLabel = this.FindControl<Label>("OccupantStatusLabel");
